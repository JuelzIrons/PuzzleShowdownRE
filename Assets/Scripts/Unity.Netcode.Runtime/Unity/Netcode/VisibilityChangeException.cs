namespace Unity.Netcode
{
	public class VisibilityChangeException : global::System.Exception
	{
		public VisibilityChangeException()
		{
		}

		public VisibilityChangeException(string message)
			: base(message)
		{
		}

		public VisibilityChangeException(string message, global::System.Exception inner)
			: base(message, inner)
		{
		}
	}
}
